"""Ingest local files into the raw (bronze) Cloud Storage zone (issue #12).

Follows docs/data/raw_zone_convention.md: files are stored byte for byte, written once,
partitioned by ingest date and named <dataset>_<yyyymmdd>_<seq>.<ext>. Each load that
writes files also writes one manifest (size, SHA-256, row count, license note, load id).

A rerun is safe. A file whose SHA-256 is already in raw for the same domain, source and
dataset is skipped, on any ingest date, so no duplicates are written. Changed content is
a re-delivery and gets the next sequence number. Every upload is create-only, so an
existing object is never overwritten. All files are checked before the first upload;
if an upload fails partway, the files already written still get a manifest marked
"partial". Dates and times are UTC. Sequence numbers run 001 to 999 per dataset per day.

Usage:
    python -m data.ingestion.ingest_raw --in .local/claims_world --local-root .local/fake_bucket
    python -m data.ingestion.ingest_raw --in .local/claims_world --dry-run
    python -m data.ingestion.ingest_raw --in .local/claims_world
The last two read the bucket from CLAIMGUARD_RAW_BUCKET and, if set, impersonate the
service account in CLAIMGUARD_INGEST_SA. Real names live in the environment, not here.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import os
import re
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Protocol

DOMAINS = {"claims_batch": ".csv"}  # v1 ingests batch CSV extracts only
SYNTHETIC_LICENSE = "Synthetic data generated by this project; no third-party terms."
MANIFEST_VERSION = 1
_SOURCE = re.compile(r"^(synthetic|public_[a-z0-9_]+)$")
_OBJECT = re.compile(r"^(?P<ds>[a-z0-9_]+)_(?P<day>\d{8})_(?P<seq>\d{3})\.")
_CHUNK = 1024 * 1024


# --- storage -------------------------------------------------------------------------

class Store(Protocol):
    def list_objects(self, prefix: str) -> dict[str, dict[str, str]]:
        """Object name -> custom metadata, for every object under `prefix`."""

    def create(self, name: str, data: Path | bytes, metadata: dict[str, str],
               content_type: str) -> None:
        """Write a new object. Raise FileExistsError if `name` already exists."""


class LocalStore:
    """A folder that behaves like a bucket, for tests and offline runs.

    Metadata sits in a sidecar file next to each object. Exclusive create ("xb") plays
    the part of the bucket's create-only precondition.
    """

    META = ".meta.json"

    def __init__(self, root: str | Path):
        self.root = Path(root)

    def list_objects(self, prefix: str) -> dict[str, dict[str, str]]:
        out: dict[str, dict[str, str]] = {}
        if not self.root.exists():
            return out
        for p in sorted(self.root.rglob("*")):
            if not p.is_file() or p.name.endswith(self.META):
                continue
            name = p.relative_to(self.root).as_posix()
            if name.startswith(prefix):
                meta = p.with_name(p.name + self.META)
                out[name] = json.loads(meta.read_text("utf-8")) if meta.exists() else {}
        return out

    def create(self, name: str, data: Path | bytes, metadata: dict[str, str],
               content_type: str) -> None:
        target = self.root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        payload = data.read_bytes() if isinstance(data, Path) else data
        with open(target, "xb") as f:  # raises FileExistsError: never overwrite
            f.write(payload)
        target.with_name(target.name + self.META).write_text(
            json.dumps(metadata, sort_keys=True), encoding="utf-8")


class GcsStore:
    """The raw Cloud Storage bucket. Uploads use if_generation_match=0 (create only)."""

    def __init__(self, bucket: str, impersonate: str | None = None):
        import google.auth
        from google.cloud import storage

        scopes = ["https://www.googleapis.com/auth/cloud-platform"]
        credentials, project = google.auth.default(scopes=scopes)
        if impersonate:  # act as the pipeline service account; no key file involved
            from google.auth import impersonated_credentials

            credentials = impersonated_credentials.Credentials(
                source_credentials=credentials, target_principal=impersonate,
                target_scopes=scopes)
        client = storage.Client(project=project, credentials=credentials)
        self._client = client
        self._bucket = client.bucket(bucket)

    def list_objects(self, prefix: str) -> dict[str, dict[str, str]]:
        blobs = self._client.list_blobs(self._bucket, prefix=prefix)
        return {b.name: dict(b.metadata or {}) for b in blobs}

    def create(self, name: str, data: Path | bytes, metadata: dict[str, str],
               content_type: str) -> None:
        from google.api_core.exceptions import PreconditionFailed

        blob = self._bucket.blob(name)
        blob.metadata = metadata
        try:
            if isinstance(data, Path):
                blob.upload_from_filename(str(data), content_type=content_type,
                                          if_generation_match=0)
            else:
                blob.upload_from_string(data, content_type=content_type,
                                        if_generation_match=0)
        except PreconditionFailed as e:
            raise FileExistsError(name) from e


# --- file facts ----------------------------------------------------------------------

def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(_CHUNK):
            h.update(chunk)
    return h.hexdigest()


def count_csv_rows(path: Path) -> int:
    """Data rows, not counting the header. Quoted line breaks stay inside one row."""
    with open(path, encoding="utf-8", errors="replace", newline="") as f:
        return max(sum(1 for _ in csv.reader(f)) - 1, 0)


def dataset_name(path: Path) -> str:
    """Lowercase, no spaces: 'Claims Data.csv' -> 'claims_data'."""
    name = re.sub(r"[^a-z0-9]+", "_", path.stem.lower()).strip("_")
    if not name:
        raise ValueError(f"cannot derive a dataset name from {path.name!r}")
    return name


# --- the load ------------------------------------------------------------------------

def ingest(in_dir: str | Path, store: Store, *, domain: str = "claims_batch",
           source: str = "synthetic", license_note: str | None = None,
           now: datetime | None = None, load_id: str | None = None,
           dry_run: bool = False) -> dict:
    """Load every file of the domain's type in `in_dir` (not subfolders) into raw.

    Returns the manifest. It is written to the store only when at least one file was
    uploaded and this is not a dry run.
    """
    if domain not in DOMAINS:
        raise ValueError(f"unsupported domain {domain!r}; v1 supports {sorted(DOMAINS)}")
    if not _SOURCE.match(source):
        raise ValueError(f"source must be 'synthetic' or 'public_<name>', got {source!r}")
    source_type = "synthetic" if source == "synthetic" else "public"
    if license_note is None and source_type == "synthetic":
        license_note = SYNTHETIC_LICENSE
    if not (license_note or "").strip():
        raise ValueError("a public source needs a license note (see the source register)")

    ext = DOMAINS[domain]
    files = sorted(p for p in Path(in_dir).glob(f"*{ext}") if p.is_file())
    if not files:
        raise ValueError(f"no {ext} files in {in_dir}")

    now = (now or datetime.now(UTC)).astimezone(UTC)
    day = now.strftime("%Y%m%d")
    ingest_date = now.date().isoformat()
    load_id = load_id or f"{now:%Y%m%dT%H%M%SZ}_{uuid.uuid4().hex[:8]}"
    base = f"{domain}/source={source}/"

    # What raw already holds for this domain and source, on any date.
    seen: dict[tuple[str, str], str] = {}  # (dataset, sha256) -> object name
    last_seq: dict[str, int] = {}          # dataset -> highest sequence used today
    for name, meta in store.list_objects(base).items():
        m = _OBJECT.match(name.rsplit("/", 1)[-1])
        if not m:
            continue  # not a file this tool names; leave it alone
        if meta.get("sha256"):
            seen[(m["ds"], meta["sha256"])] = name
        if m["day"] == day:
            last_seq[m["ds"]] = max(last_seq.get(m["ds"], 0), int(m["seq"]))

    # Phase 1: work out every file's facts before writing anything, so a bad file
    # stops the load before the first upload.
    planned: list[tuple[Path, dict]] = []
    skipped: list[dict] = []
    for path in files:
        ds, sha = dataset_name(path), sha256_of(path)
        if (ds, sha) in seen:
            skipped.append({"original_name": path.name, "sha256": sha,
                            "existing_object": seen[(ds, sha)]})
            continue
        seq = last_seq.get(ds, 0) + 1
        last_seq[ds] = seq
        obj = f"{base}ingest_date={ingest_date}/{ds}_{day}_{seq:03d}{ext}"
        seen[(ds, sha)] = obj
        planned.append((path, {
            "object": obj,
            "original_name": path.name,
            "dataset": ds,
            "size_bytes": path.stat().st_size,
            "sha256": sha,
            "row_count": count_csv_rows(path),
        }))

    # Phase 2: upload. If it stops partway, the files already written still get a
    # manifest (status "partial"), then the error is raised again.
    uploaded: list[dict] = []

    def finish(status: str, error: str | None) -> dict:
        manifest = {
            "manifest_version": MANIFEST_VERSION,
            "load_id": load_id,
            "ingest_time": now.isoformat().replace("+00:00", "Z"),
            "domain": domain,
            "source": source,
            "source_type": source_type,
            "license_note": license_note,
            "dry_run": dry_run,
            "status": status,
            "error": error,
            "files": uploaded,
            "skipped": skipped,
            "manifest_object": None,
        }
        if uploaded and not dry_run:
            mobj = f"_manifests/source={source}/ingest_date={ingest_date}/load_{load_id}.json"
            manifest["manifest_object"] = mobj
            body = (json.dumps(manifest, indent=2) + "\n").encode("utf-8")
            store.create(mobj, body, {"load_id": load_id}, "application/json")
        return manifest

    try:
        for path, entry in planned:
            if not dry_run:
                meta = {"dataset": entry["dataset"], "sha256": entry["sha256"],
                        "load_id": load_id, "original_name": path.name,
                        "row_count": str(entry["row_count"])}
                store.create(entry["object"], path, meta, "text/csv")
            uploaded.append(entry)
    except Exception as e:
        finish("partial", f"{type(e).__name__}: {e}")
        raise
    return finish("complete", None)


# --- command line --------------------------------------------------------------------

def main(argv: list[str] | None = None) -> dict:
    p = argparse.ArgumentParser(description="Load local files into the raw zone.")
    p.add_argument("--in", dest="in_dir", type=Path, required=True)
    p.add_argument("--domain", default="claims_batch")
    p.add_argument("--source", default="synthetic")
    p.add_argument("--license-note")
    p.add_argument("--bucket", default=os.environ.get("CLAIMGUARD_RAW_BUCKET"))
    p.add_argument("--impersonate", default=os.environ.get("CLAIMGUARD_INGEST_SA"),
                   help="service account email to act as (no key file)")
    p.add_argument("--local-root", type=Path, help="use a local folder instead of GCS")
    p.add_argument("--dry-run", action="store_true", help="plan only; write nothing")
    a = p.parse_args(argv)

    if a.local_root:
        store: Store = LocalStore(a.local_root)
    elif a.bucket:
        store = GcsStore(a.bucket, a.impersonate)
    else:
        p.error("set --bucket (or CLAIMGUARD_RAW_BUCKET) or --local-root")

    m = ingest(a.in_dir, store, domain=a.domain, source=a.source,
               license_note=a.license_note, dry_run=a.dry_run)
    summary = {"load_id": m["load_id"], "dry_run": m["dry_run"],
               "uploaded": len(m["files"]), "skipped": len(m["skipped"]),
               "manifest_object": m["manifest_object"]}
    for f in m["files"]:
        print(("would upload " if a.dry_run else "uploaded ") + f["object"],
              f"({f['row_count']} rows)")
    for f in m["skipped"]:
        print(f"skipped {f['original_name']} (same bytes as {f['existing_object']})")
    print(json.dumps(summary))
    return m


if __name__ == "__main__":
    main()
